export type Copy = Readonly<Record<keyof typeof en, string>>

export const T: Readonly<Record<Lang, Copy>> = { en, fil }

export function loadLang(): Lang {
  try {
    const v = window.localStorage.getItem('atrium.lang')
    return v === 'fil' ? 'fil' : 'en'
  } catch {
    return 'en'
  }
}

export function saveLang(lang: Lang): void {
  try {
    window.localStorage.setItem('atrium.lang', lang)
  } catch {
    // per-viewer convenience only
  }
}
